package com.feelm.backend.infrastructure.mail;

/**
 * 계정 메일(가입 인증, 비밀번호 재설정)을 보낸다.
 *
 * <p>구현 교체 지점을 인터페이스로 둔 이유는 두 가지다. 하나는 실제 SMTP 발송과 로컬 확인용 로그 출력을 환경별로 바꿔야 하기 때문이고(플랜 결정 5·6), 다른
 * 하나는 토큰 원문을 DB에서 되돌릴 수 없어(결정 8) 테스트가 발송 지점을 대체해 원문을 확인해야 하기 때문이다(결정 13).
 *
 * <p><b>종류별로 인터페이스를 나누지 않는다</b>(S15P21E106-284). 나눠 두었던 이유는 "메일 종류마다 링크·본문·수명이 달라 한쪽 변경이 다른 쪽 서명으로
 * 번지지 않게" 하려는 것이었지만(S15P21E106-151 결정 E), 실제로 종류마다 달라지는 것은 <b>값</b>(제목·본문·링크)이고 서명은 같았다. 값을 {@link
 * MailKind}와 {@link AuthMailProperties}로 모으면 그 우려를 지키면서 발송 구현은 하나로 남는다. 세 번째 메일 종류가 생겨도 인터페이스와 구현체,
 * 조건부 빈, 테스트 스파이를 새로 만들지 않고 열거형에 값을 추가한다.
 */
public interface AuthMailSender {

    /**
     * 해당 종류의 링크가 담긴 메일을 보낸다.
     *
     * @param kind 메일 종류. 제목·본문과 링크가 갈 화면을 정한다
     * @param email 수신 주소
     * @param rawToken 1회용 토큰 원문. 링크에만 사용하고 저장·로그에 남기지 않는다(컨벤션 12장)
     */
    void send(MailKind kind, String email, String rawToken);
}
