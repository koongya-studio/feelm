-- 마감 준비가 정상 완료되었는지 기록한다. 대상 사용자 0명도 성공으로 보존한다(S15P21E106-555).
CREATE TABLE taste_report_generation_runs (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year           smallint NOT NULL,
    half           varchar(2) NOT NULL,
    snapshot_at    timestamptz NOT NULL,
    prepared_count integer NOT NULL,
    completed_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_taste_report_generation_runs_year_half UNIQUE (year, half),
    CONSTRAINT ck_taste_report_generation_runs_half CHECK (half IN ('H1', 'H2')),
    CONSTRAINT ck_taste_report_generation_runs_prepared_count CHECK (prepared_count >= 0)
);
