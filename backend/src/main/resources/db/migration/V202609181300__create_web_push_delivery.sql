-- S15P21E106-582: 브라우저별 Web Push 구독과 durable delivery를 저장한다.
-- endpoint와 구독 키는 발송에 필요한 capability 정보이므로 활성 구독에만 보관하고,
-- 해제·만료 시 원문을 지운 뒤 SHA-256 fingerprint와 비민감 발송 결과만 남긴다.
CREATE TABLE web_push_subscriptions (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              bigint NOT NULL,
    endpoint             text,
    endpoint_fingerprint char(64) NOT NULL,
    p256dh_key           text,
    auth_secret          text,
    expiration_at        timestamptz,
    active               boolean NOT NULL DEFAULT true,
    capability_version   bigint NOT NULL,
    deactivated_at       timestamptz,
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_web_push_subscriptions_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_web_push_subscriptions_endpoint_fingerprint
        UNIQUE (endpoint_fingerprint),
    CONSTRAINT ck_web_push_subscriptions_material CHECK (
        (active AND endpoint IS NOT NULL AND p256dh_key IS NOT NULL
            AND auth_secret IS NOT NULL AND deactivated_at IS NULL)
        OR
        (NOT active AND endpoint IS NULL AND p256dh_key IS NULL
            AND auth_secret IS NULL AND deactivated_at IS NOT NULL)
    ),
    CONSTRAINT ck_web_push_subscriptions_fingerprint CHECK (
        endpoint_fingerprint ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT ck_web_push_subscriptions_capability_version CHECK (
        capability_version > 0
    )
);

CREATE INDEX ix_web_push_subscriptions_user_active
    ON web_push_subscriptions (user_id, id)
    WHERE active;

CREATE TABLE web_push_deliveries (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id      bigint NOT NULL,
    subscription_id      bigint,
    endpoint_fingerprint char(64) NOT NULL,
    status               varchar(20) NOT NULL,
    attempt_count        integer NOT NULL DEFAULT 0,
    next_attempt_at      timestamptz NOT NULL,
    claimed_at           timestamptz,
    claim_token          uuid,
    delivered_at         timestamptz,
    finished_at          timestamptz,
    last_http_status     integer,
    failure_code         varchar(50),
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_web_push_deliveries_notification_id FOREIGN KEY (notification_id)
        REFERENCES notifications (id) ON DELETE CASCADE,
    CONSTRAINT fk_web_push_deliveries_subscription_id FOREIGN KEY (subscription_id)
        REFERENCES web_push_subscriptions (id) ON DELETE SET NULL,
    CONSTRAINT uk_web_push_deliveries_notification_endpoint
        UNIQUE (notification_id, endpoint_fingerprint),
    CONSTRAINT ck_web_push_deliveries_status CHECK (
        status IN ('PENDING', 'PROCESSING', 'SENT', 'FAILED', 'CANCELED')
    ),
    CONSTRAINT ck_web_push_deliveries_attempt_count CHECK (attempt_count >= 0),
    CONSTRAINT ck_web_push_deliveries_claim CHECK (
        (status = 'PROCESSING' AND claimed_at IS NOT NULL AND claim_token IS NOT NULL)
        OR
        (status <> 'PROCESSING' AND claimed_at IS NULL AND claim_token IS NULL)
    ),
    CONSTRAINT ck_web_push_deliveries_http_status CHECK (
        last_http_status IS NULL OR last_http_status BETWEEN 100 AND 599
    ),
    CONSTRAINT ck_web_push_deliveries_fingerprint CHECK (
        endpoint_fingerprint ~ '^[0-9a-f]{64}$'
    )
);

-- due polling과 stale lease 회수의 공통 접근 경로다.
CREATE INDEX ix_web_push_deliveries_due
    ON web_push_deliveries (next_attempt_at, id)
    WHERE status IN ('PENDING', 'PROCESSING');

CREATE INDEX ix_web_push_deliveries_subscription_pending
    ON web_push_deliveries (subscription_id, id)
    WHERE status IN ('PENDING', 'PROCESSING');
