CREATE TABLE party_popcorn_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id bigint NOT NULL CONSTRAINT fk_party_popcorn_snapshots_party_id REFERENCES parties(id) ON DELETE CASCADE,
    set_id bigint NOT NULL CONSTRAINT fk_party_popcorn_snapshots_set_id REFERENCES recommendation_sets(id) ON DELETE CASCADE,
    exposed_at timestamptz NOT NULL,
    members jsonb NOT NULL,
    recommendation_mode varchar(20) NOT NULL CONSTRAINT ck_party_popcorn_snapshots_recommendation_mode CHECK (recommendation_mode IN ('PERSONALIZED','POPULARITY')),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_party_popcorn_snapshots_set_id_exposed_at UNIQUE(set_id, exposed_at)
);
CREATE INDEX ix_party_popcorn_snapshots_latest ON party_popcorn_snapshots(party_id, exposed_at DESC, id DESC);
