-- 콘텐츠·감상 도메인(S15P21E106-180). 공통 선행 마이그레이션의 기준 테이블을 참조한다.
-- 사용자 탈퇴는 users.status 전이로 처리하며, 이 마이그레이션은 물리 삭제를 전파하지 않는다.

-- 영화와 장르의 다대다 관계. 영화 상세는 movie_id, 장르 필터는 genre_id로 조회한다.
CREATE TABLE movie_genres (
    movie_id bigint NOT NULL,
    genre_id bigint NOT NULL,
    PRIMARY KEY (movie_id, genre_id),
    CONSTRAINT fk_movie_genres_movie_id FOREIGN KEY (movie_id)
        REFERENCES movies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_movie_genres_genre_id FOREIGN KEY (genre_id)
        REFERENCES genres (id) ON DELETE RESTRICT
);

CREATE INDEX ix_movie_genres_genre_id ON movie_genres (genre_id);


-- 국가 기준 테이블은 두지 않고 TMDb의 ISO 3166-1 alpha-2 코드를 영화에 연결한다.
CREATE TABLE movie_countries (
    movie_id    bigint NOT NULL,
    country_code varchar(2) NOT NULL,
    PRIMARY KEY (movie_id, country_code),
    CONSTRAINT fk_movie_countries_movie_id FOREIGN KEY (movie_id)
        REFERENCES movies (id) ON DELETE RESTRICT,
    CONSTRAINT ck_movie_countries_country_code
        CHECK (country_code ~ '^[A-Z]{2}$')
);

CREATE INDEX ix_movie_countries_country_code ON movie_countries (country_code);


-- 영화 크레딧. 같은 인물이 한 영화에서 감독과 배우 역할을 함께 가질 수 있어 role도 PK에 포함한다.
CREATE TABLE movie_people (
    movie_id      bigint NOT NULL,
    person_id     bigint NOT NULL,
    role          varchar(10) NOT NULL,
    character_name text,
    display_order int,
    PRIMARY KEY (movie_id, person_id, role),
    CONSTRAINT fk_movie_people_movie_id FOREIGN KEY (movie_id)
        REFERENCES movies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_movie_people_person_id FOREIGN KEY (person_id)
        REFERENCES people (id) ON DELETE RESTRICT,
    CONSTRAINT ck_movie_people_role CHECK (role IN ('DIRECTOR', 'ACTOR'))
);

CREATE INDEX ix_movie_people_person_id ON movie_people (person_id);


-- TMDb watch provider 동기화 결과. URL과 동기화 시각은 원천 데이터에 없을 수 있다.
CREATE TABLE movie_ott_providers (
    movie_id bigint NOT NULL,
    ott_id   bigint NOT NULL,
    watch_url text,
    synced_at timestamptz,
    PRIMARY KEY (movie_id, ott_id),
    CONSTRAINT fk_movie_ott_providers_movie_id FOREIGN KEY (movie_id)
        REFERENCES movies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_movie_ott_providers_ott_id FOREIGN KEY (ott_id)
        REFERENCES otts (id) ON DELETE RESTRICT
);

CREATE INDEX ix_movie_ott_providers_ott_id ON movie_ott_providers (ott_id);


-- 감상 상태 머신. 상태별 시각은 해당 전이가 일어나기 전까지 NULL이다.
CREATE TABLE watch_records (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        bigint NOT NULL,
    movie_id       bigint NOT NULL,
    ott_id         bigint,
    status         varchar(30) NOT NULL,
    clicked_at     timestamptz,
    confirm_due_at timestamptz,
    expires_at     timestamptz,
    watched_at     timestamptz,
    rated_at       timestamptz,
    expired_at     timestamptz,
    CONSTRAINT fk_watch_records_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_watch_records_movie_id FOREIGN KEY (movie_id)
        REFERENCES movies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_watch_records_ott_id FOREIGN KEY (ott_id)
        REFERENCES otts (id) ON DELETE RESTRICT,
    CONSTRAINT ck_watch_records_status
        CHECK (status IN ('LINK_CLICKED', 'WATCHED_UNRATED', 'RATED', 'EXPIRED'))
);

-- 만료된 기록은 이력으로 남기고, 사용자·영화별 활성 기록은 하나만 유지한다(D-6).
CREATE UNIQUE INDEX uix_watch_records_active_user_movie
    ON watch_records (user_id, movie_id)
    WHERE status <> 'EXPIRED';

-- 감상 기록 목록은 NULL 클릭 시각을 뒤로 보내고 id로 정렬 순서를 고정한다(API-034).
CREATE INDEX ix_watch_records_user_id_clicked_at
    ON watch_records (user_id, clicked_at DESC NULLS LAST, id DESC);


-- 평가와 선택적 한줄평. 감상 기록 없이 평가할 수 있어 watch_record_id는 NULL을 허용한다(D-6).
CREATE TABLE ratings (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint NOT NULL,
    movie_id        bigint NOT NULL,
    watch_record_id bigint,
    score           smallint NOT NULL,
    comment         varchar(200),
    visibility      varchar(10),
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_ratings_user_id_movie_id UNIQUE (user_id, movie_id),
    CONSTRAINT fk_ratings_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ratings_movie_id FOREIGN KEY (movie_id)
        REFERENCES movies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ratings_watch_record_id FOREIGN KEY (watch_record_id)
        REFERENCES watch_records (id) ON DELETE RESTRICT,
    CONSTRAINT ck_ratings_score_range CHECK (score >= 1 AND score <= 5),
    CONSTRAINT ck_ratings_visibility
        CHECK (visibility IN ('PUBLIC', 'PRIVATE')),
    CONSTRAINT ck_ratings_comment_requires_visibility
        CHECK (comment IS NULL OR visibility IS NOT NULL)
);

-- 공개 한줄평·영화별 평가 집계는 movie_id로 조회한다. 사용자별 조회는 UK 선두 컬럼을 사용한다.
CREATE INDEX ix_ratings_movie_id ON ratings (movie_id);

-- 감상 기록 목록에서 연결된 평가 ID를 조회한다(API-034).
CREATE INDEX ix_ratings_watch_record_id ON ratings (watch_record_id);
