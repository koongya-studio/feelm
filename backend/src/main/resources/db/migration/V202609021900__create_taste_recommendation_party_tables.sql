ALTER TABLE movies DROP COLUMN taste_model_version;


-- 평가 변경 시 Spring이 갱신하는 사용자별 취향 분석 캐시.
CREATE TABLE taste_analyses (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      bigint NOT NULL,
    analysis     jsonb NOT NULL,
    keywords     jsonb NOT NULL,
    rating_count int NOT NULL,
    analyzed_at  timestamptz NOT NULL,
    CONSTRAINT uk_taste_analyses_user_id UNIQUE (user_id),
    CONSTRAINT fk_taste_analyses_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_taste_analyses_rating_count CHECK (rating_count >= 0)
);


-- 필름의 프레임. user_id와 movie_id는 목록 조회를 위한 반정규화 컬럼이다.
CREATE TABLE frames (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rating_id  bigint NOT NULL,
    user_id    bigint NOT NULL,
    movie_id   bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_frames_rating_id UNIQUE (rating_id),
    CONSTRAINT fk_frames_rating_id FOREIGN KEY (rating_id)
        REFERENCES ratings (id) ON DELETE CASCADE,
    CONSTRAINT fk_frames_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_frames_movie_id FOREIGN KEY (movie_id)
        REFERENCES movies (id) ON DELETE RESTRICT
);

CREATE INDEX ix_frames_user_id ON frames (user_id);
CREATE INDEX ix_frames_movie_id ON frames (movie_id);


-- 파티는 종료 후에도 추천 이력과 함께 보존한다.
CREATE TABLE parties (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(20) NOT NULL,
    owner_id      bigint NOT NULL,
    status        varchar(30) NOT NULL,
    closed_reason varchar(30),
    created_at    timestamptz NOT NULL DEFAULT now(),
    closed_at     timestamptz,
    CONSTRAINT fk_parties_owner_id FOREIGN KEY (owner_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_parties_status CHECK (status IN ('ACTIVE', 'CLOSED')),
    CONSTRAINT ck_parties_closed_reason
        CHECK (closed_reason IN ('INSUFFICIENT_MEMBERS', 'OWNER_CLOSED')),
    CONSTRAINT ck_parties_closed_state CHECK (
        (status = 'ACTIVE' AND closed_reason IS NULL AND closed_at IS NULL)
        OR (status = 'CLOSED' AND closed_reason IS NOT NULL AND closed_at IS NOT NULL)
    )
);

CREATE INDEX ix_parties_owner_id ON parties (owner_id);
CREATE INDEX ix_parties_status ON parties (status);


-- 오너도 멤버 행으로 저장한다. OWNER 존재와 parties.owner_id 일치는 애플리케이션이 보장한다.
CREATE TABLE party_members (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id bigint NOT NULL,
    user_id   bigint NOT NULL,
    role      varchar(30) NOT NULL,
    joined_at timestamptz NOT NULL,
    CONSTRAINT uk_party_members_party_user UNIQUE (party_id, user_id),
    CONSTRAINT fk_party_members_party_id FOREIGN KEY (party_id)
        REFERENCES parties (id) ON DELETE CASCADE,
    CONSTRAINT fk_party_members_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_party_members_role CHECK (role IN ('OWNER', 'MEMBER'))
);

CREATE UNIQUE INDEX uix_party_members_single_owner
    ON party_members (party_id) WHERE role = 'OWNER';
CREATE INDEX ix_party_members_user_id ON party_members (user_id);


-- 현재 파티원 누구나 초대할 수 있으며 초대 이력은 초대자가 나가도 보존한다.
CREATE TABLE party_invitations (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id     bigint NOT NULL,
    inviter_id   bigint NOT NULL,
    invitee_id   bigint NOT NULL,
    status       varchar(30) NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    responded_at timestamptz,
    CONSTRAINT fk_party_invitations_party_id FOREIGN KEY (party_id)
        REFERENCES parties (id) ON DELETE CASCADE,
    CONSTRAINT fk_party_invitations_inviter_id FOREIGN KEY (inviter_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_party_invitations_invitee_id FOREIGN KEY (invitee_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_party_invitations_status
        CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED')),
    CONSTRAINT ck_party_invitations_response_state CHECK (
        (status = 'PENDING' AND responded_at IS NULL)
        OR (status IN ('ACCEPTED', 'DECLINED') AND responded_at IS NOT NULL)
    ),
    CONSTRAINT ck_party_invitations_not_self CHECK (inviter_id <> invitee_id)
);

CREATE UNIQUE INDEX uix_party_invitations_pending
    ON party_invitations (party_id, invitee_id) WHERE status = 'PENDING';
CREATE INDEX ix_party_invitations_inviter_id ON party_invitations (inviter_id);
CREATE INDEX ix_party_invitations_invitee_id ON party_invitations (invitee_id);
CREATE INDEX ix_party_invitations_status ON party_invitations (status);


-- 개인 추천과 파티 추천은 user_id와 party_id의 배타 관계로 구분한다.
CREATE TABLE recommendation_sets (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       bigint,
    party_id      bigint,
    input_version varchar(100) NOT NULL,
    model_version varchar(50) NOT NULL,
    generated_at  timestamptz NOT NULL,
    CONSTRAINT fk_recommendation_sets_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_recommendation_sets_party_id FOREIGN KEY (party_id)
        REFERENCES parties (id) ON DELETE RESTRICT,
    CONSTRAINT ck_recommendation_sets_owner
        CHECK ((user_id IS NULL) <> (party_id IS NULL))
);

CREATE UNIQUE INDEX uix_recommendation_sets_user_input_model
    ON recommendation_sets (user_id, input_version, model_version)
    WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX uix_recommendation_sets_party_input_model
    ON recommendation_sets (party_id, input_version, model_version)
    WHERE party_id IS NOT NULL;
CREATE INDEX ix_recommendation_sets_user_id_generated_at
    ON recommendation_sets (user_id, generated_at DESC);
CREATE INDEX ix_recommendation_sets_party_id_generated_at
    ON recommendation_sets (party_id, generated_at DESC);


-- 한 세트의 후보 20편을 모두 저장하고 exposed_at으로 실제 노출 여부를 구분한다.
CREATE TABLE recommendation_items (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_id     bigint NOT NULL,
    movie_id   bigint NOT NULL,
    type       varchar(30) NOT NULL,
    position   int NOT NULL,
    reason     jsonb NOT NULL,
    exposed_at timestamptz,
    CONSTRAINT uk_recommendation_items_set_position UNIQUE (set_id, position),
    CONSTRAINT uk_recommendation_items_set_movie UNIQUE (set_id, movie_id),
    CONSTRAINT fk_recommendation_items_set_id FOREIGN KEY (set_id)
        REFERENCES recommendation_sets (id) ON DELETE CASCADE,
    CONSTRAINT fk_recommendation_items_movie_id FOREIGN KEY (movie_id)
        REFERENCES movies (id) ON DELETE RESTRICT,
    CONSTRAINT ck_recommendation_items_type
        CHECK (type IN ('TASTE', 'DISCOVERY', 'PARTY')),
    CONSTRAINT ck_recommendation_items_position CHECK (position >= 1)
);

CREATE INDEX ix_recommendation_items_movie_id ON recommendation_items (movie_id);


-- 관심없음은 추천과 독립적인 사용자-영화 관계다. 추천 아이템은 선택적인 출처 정보다.
CREATE TABLE user_movie_dismissals (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                bigint NOT NULL,
    movie_id               bigint NOT NULL,
    recommendation_item_id bigint,
    created_at             timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_user_movie_dismissals_user_movie UNIQUE (user_id, movie_id),
    CONSTRAINT fk_user_movie_dismissals_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_movie_dismissals_movie_id FOREIGN KEY (movie_id)
        REFERENCES movies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_movie_dismissals_recommendation_item_id
        FOREIGN KEY (recommendation_item_id)
        REFERENCES recommendation_items (id) ON DELETE SET NULL
);

CREATE INDEX ix_user_movie_dismissals_movie_id ON user_movie_dismissals (movie_id);
CREATE INDEX ix_user_movie_dismissals_recommendation_item_id
    ON user_movie_dismissals (recommendation_item_id);
