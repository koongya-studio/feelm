-- 계정·온보딩 도메인(S15P21E106-179). 공통 선행 마이그레이션의 users, movies, otts를 참조한다.
-- 명명·타입·삭제 정책은 docs/db-schema-convention.md를 따른다.
-- 탈퇴는 물리 삭제가 아니라 status 전이 + 익명화 치환이므로(D-9 계정 영역 확정) 아래 CASCADE는
-- 평상시 발동하지 않는다. 개인정보 삭제 요청에 대응하기 위해 정의만 남긴다.

-- 소셜 로그인 수단. 같은 이메일이어도 기존 계정에 자동 통합하지 않는다(ERD 2.1).
CREATE TABLE user_auth_providers (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          bigint NOT NULL,
    provider         varchar(20) NOT NULL,
    -- 제공자가 발급한 불투명 식별자. 계약상 상한이 없어 text를 쓴다.
    provider_user_id text NOT NULL,
    linked_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_user_auth_providers_provider_provider_user_id
        UNIQUE (provider, provider_user_id),
    CONSTRAINT uk_user_auth_providers_user_id_provider
        UNIQUE (user_id, provider),
    CONSTRAINT fk_user_auth_providers_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_user_auth_providers_provider
        CHECK (provider IN ('GOOGLE', 'KAKAO', 'NAVER'))
);

-- 사용자별 로그인·연결 조회는 (user_id, provider) UK 인덱스를 탄다.


-- 가입 이메일 인증 토큰. 1회용이며 만료 24시간이다(API-001 가정).
-- 원문은 저장하지 않고 해시만 둔다. 해시 알고리즘은 구현 결정이라 길이를 고정하지 않는다.
CREATE TABLE email_verification_tokens (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint NOT NULL,
    token_hash text NOT NULL,
    expires_at timestamptz NOT NULL,
    -- 사용 전에는 NULL이다. 값이 있으면 소진된 토큰이다.
    used_at    timestamptz,
    CONSTRAINT uk_email_verification_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_email_verification_tokens_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
);

-- 인증 메일 재발송(API-003)이 사용자별 최신 토큰을 찾는다.
CREATE INDEX ix_email_verification_tokens_user_id ON email_verification_tokens (user_id);


-- 비밀번호 재설정 토큰. 1회용이며 만료 30분이다(API-010 가정).
CREATE TABLE password_reset_tokens (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint NOT NULL,
    token_hash text NOT NULL,
    expires_at timestamptz NOT NULL,
    used_at    timestamptz,
    CONSTRAINT uk_password_reset_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_password_reset_tokens_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
);

-- 재설정 요청이 사용자별 유효 토큰을 확인한다.
CREATE INDEX ix_password_reset_tokens_user_id ON password_reset_tokens (user_id);


-- 알림 수신 설정. 사용자당 1행이므로 user_id가 기본키이자 외래키다.
-- 기본값은 API-017 처리 규칙과 맞춘다. 공통 규칙의 boolean 기본값(false)에 대한 예외다.
CREATE TABLE notification_settings (
    user_id                bigint PRIMARY KEY,
    rating_enabled         boolean NOT NULL DEFAULT true,
    recommendation_enabled boolean NOT NULL DEFAULT true,
    marketing_enabled      boolean NOT NULL DEFAULT false,
    CONSTRAINT fk_notification_settings_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
);


-- 사용자 차단. 양방향 노출 차단은 조회 시 OR 조건으로 처리한다(ERD 2.1).
CREATE TABLE user_blocks (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id bigint NOT NULL,
    blocked_id bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_user_blocks_blocker_id_blocked_id UNIQUE (blocker_id, blocked_id),
    CONSTRAINT fk_user_blocks_blocker_id FOREIGN KEY (blocker_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_blocks_blocked_id FOREIGN KEY (blocked_id)
        REFERENCES users (id) ON DELETE CASCADE,
    -- API-020의 CANNOT_BLOCK_SELF를 DB에서도 보장한다.
    CONSTRAINT ck_user_blocks_not_self CHECK (blocker_id <> blocked_id)
);

-- 차단 목록(API-022)은 UK 선두 컬럼으로 조회되지만, 나를 차단한 사용자를 찾는 역방향
-- 필터에는 인덱스가 없다. 검색·파티 초대 후보 제외가 이 경로를 쓴다.
CREATE INDEX ix_user_blocks_blocked_id ON user_blocks (blocked_id);


-- 온보딩 초기 취향. 평가(1~5점)와 분리 저장하며 프레임·팝콘을 만들지 않는다(API-024).
CREATE TABLE onboarding_preferences (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint NOT NULL,
    movie_id   bigint NOT NULL,
    preference varchar(10) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_onboarding_preferences_user_id_movie_id UNIQUE (user_id, movie_id),
    CONSTRAINT fk_onboarding_preferences_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    -- 기준정보는 삭제하지 않으므로 RESTRICT다.
    CONSTRAINT fk_onboarding_preferences_movie_id FOREIGN KEY (movie_id)
        REFERENCES movies (id) ON DELETE RESTRICT,
    CONSTRAINT ck_onboarding_preferences_preference
        CHECK (preference IN ('LIKE', 'DISLIKE'))
);

-- movie_id 단독 조회 경로가 없어(추천 입력은 사용자 기준으로 읽는다) 별도 인덱스를 두지 않는다.
-- UK의 선두 컬럼이 user_id라 사용자별 조회는 UK 인덱스를 탄다.


-- 구독 OTT. 전체 교체(PUT)이므로 대리키 없이 복합 기본키를 쓴다(API-027).
CREATE TABLE user_otts (
    user_id bigint NOT NULL,
    ott_id  bigint NOT NULL,
    PRIMARY KEY (user_id, ott_id),
    CONSTRAINT fk_user_otts_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_otts_ott_id FOREIGN KEY (ott_id)
        REFERENCES otts (id) ON DELETE RESTRICT
);

-- ott_id 단독 조회 경로가 없어(구독 목록은 사용자 기준이다) 별도 인덱스를 두지 않는다.
