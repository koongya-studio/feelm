-- 반기 취향 리포트와 비공개 이미지 카드의 저장 기반(S15P21E106-554).
CREATE TABLE taste_reports (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint NOT NULL,
    year       smallint NOT NULL,
    half       varchar(2) NOT NULL,
    status     varchar(10) NOT NULL,
    content    jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_taste_reports_user_id_year_half UNIQUE (user_id, year, half),
    CONSTRAINT fk_taste_reports_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_taste_reports_half CHECK (half IN ('H1', 'H2')),
    CONSTRAINT ck_taste_reports_status CHECK (status IN ('GENERATING', 'READY'))
);

-- 이미지 파일은 스토리지에 보관하고 DB에는 비공개 버킷의 키만 저장한다.
CREATE TABLE report_images (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id   bigint NOT NULL,
    storage_key text NOT NULL,
    format      varchar(3) NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_report_images_report_id FOREIGN KEY (report_id)
        REFERENCES taste_reports (id) ON DELETE CASCADE,
    CONSTRAINT ck_report_images_format CHECK (format = 'PNG')
);

CREATE INDEX ix_report_images_report_id ON report_images (report_id);
