CREATE TABLE user_feedback (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    category varchar(20) NOT NULL,
    satisfaction varchar(20),
    comment varchar(1000),
    screen_path varchar(300) NOT NULL,
    movie_id bigint,
    recommendation_type varchar(30),
    created_at timestamptz NOT NULL DEFAULT now(),
    notification_sent_at timestamptz,
    CONSTRAINT ck_user_feedback_category CHECK (category IN ('GENERAL', 'RECOMMENDATION')),
    CONSTRAINT ck_user_feedback_satisfaction CHECK (satisfaction IS NULL OR satisfaction IN ('GOOD', 'MIXED', 'BAD')),
    CONSTRAINT ck_user_feedback_content CHECK (satisfaction IS NOT NULL OR length(trim(comment)) > 0)
);

CREATE INDEX idx_user_feedback_created_at ON user_feedback (created_at DESC);
CREATE INDEX idx_user_feedback_pending_notification ON user_feedback (id)
    WHERE notification_sent_at IS NULL;

-- 계정 탈퇴는 users 행을 삭제하지 않고 WITHDRAWN으로 변경한다.
CREATE FUNCTION delete_user_feedback_on_withdrawal() RETURNS trigger AS $$
BEGIN
    DELETE FROM user_feedback WHERE user_id = NEW.id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_delete_user_feedback_on_withdrawal
AFTER UPDATE OF status ON users
FOR EACH ROW
WHEN (OLD.status IS DISTINCT FROM 'WITHDRAWN' AND NEW.status = 'WITHDRAWN')
EXECUTE FUNCTION delete_user_feedback_on_withdrawal();
