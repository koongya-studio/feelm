-- 2차 인앱 알림(S15P21E106-581). 도메인 원본과 같은 트랜잭션에서 생성하며,
-- Web Push 전달은 후속 S15P21E106-582가 이 테이블을 정본으로 사용한다.
CREATE TABLE notifications (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint NOT NULL,
    type        varchar(30) NOT NULL,
    source_id   bigint NOT NULL,
    target_type varchar(30) NOT NULL,
    target_id   bigint NOT NULL,
    title       varchar(100) NOT NULL,
    body        varchar(300) NOT NULL,
    notified_at timestamptz NOT NULL,
    expires_at  timestamptz NOT NULL,
    read_at     timestamptz,
    closed_at   timestamptz,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_notifications_type_source UNIQUE (type, source_id),
    CONSTRAINT fk_notifications_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_notifications_type
        CHECK (type IN ('PARTY_INVITE', 'WATCH_CONFIRM')),
    CONSTRAINT ck_notifications_target_type
        CHECK (target_type IN ('PARTY_INVITATION', 'WATCH_RECORD')),
    CONSTRAINT ck_notifications_type_target CHECK (
        (type = 'PARTY_INVITE' AND target_type = 'PARTY_INVITATION')
        OR (type = 'WATCH_CONFIRM' AND target_type = 'WATCH_RECORD')
    ),
    CONSTRAINT ck_notifications_positive_references CHECK (source_id > 0 AND target_id > 0),
    CONSTRAINT ck_notifications_nonblank_copy CHECK (
        length(btrim(title)) > 0 AND length(btrim(body)) > 0
    ),
    CONSTRAINT ck_notifications_visibility_window CHECK (expires_at > notified_at)
);

-- 목록은 사용자별 활성 행을 notified_at, id 최신순으로 읽는다.
CREATE INDEX ix_notifications_user_notified
    ON notifications (user_id, notified_at DESC, id DESC);

-- 미확인 개수와 전체 읽음 처리는 열린 미확인 행만 대상으로 한다.
CREATE INDEX ix_notifications_user_unread
    ON notifications (user_id, notified_at DESC, id DESC)
    WHERE read_at IS NULL AND closed_at IS NULL;

-- 정리 작업은 만료 경계를 기준으로 삭제한다.
CREATE INDEX ix_notifications_expires_at ON notifications (expires_at);

-- 배포 전에 생성된 활성 원본도 새 알림 정본으로 이관한다. 이후 변경은 애플리케이션이
-- 원본 도메인과 같은 트랜잭션에서 notifications에 반영한다.
INSERT INTO notifications (
    user_id, type, source_id, target_type, target_id, title, body,
    notified_at, expires_at, created_at
)
SELECT
    invitation.invitee_id,
    'PARTY_INVITE',
    invitation.id,
    'PARTY_INVITATION',
    invitation.id,
    '파티 모드 초대',
    '새로운 파티 초대가 도착했어요.',
    invitation.created_at,
    invitation.created_at + interval '90 days',
    invitation.created_at
FROM party_invitations invitation
JOIN parties party ON party.id = invitation.party_id
JOIN users invitee ON invitee.id = invitation.invitee_id
WHERE invitation.status = 'PENDING'
  AND party.status = 'ACTIVE'
  AND invitee.status = 'ACTIVE'
  AND invitation.created_at + interval '90 days' > now()
ON CONFLICT (type, source_id) DO NOTHING;

INSERT INTO notifications (
    user_id, type, source_id, target_type, target_id, title, body,
    notified_at, expires_at
)
SELECT
    watch.user_id,
    'WATCH_CONFIRM',
    watch.id,
    'WATCH_RECORD',
    watch.id,
    '영화 잘 보셨나요?',
    '감상 여부를 알려주세요.',
    watch.confirm_due_at,
    watch.expires_at
FROM watch_records watch
JOIN users viewer ON viewer.id = watch.user_id
WHERE watch.status = 'LINK_CLICKED'
  AND viewer.status = 'ACTIVE'
  AND watch.confirm_due_at IS NOT NULL
  AND watch.expires_at IS NOT NULL
  AND watch.expires_at > watch.confirm_due_at
  AND watch.expires_at > now()
ON CONFLICT (type, source_id) DO NOTHING;
