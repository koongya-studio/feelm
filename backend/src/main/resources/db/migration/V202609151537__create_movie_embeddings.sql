-- 영화별 현재 콘텐츠 임베딩을 PostgreSQL/pgvector에 저장한다(S15P21E106-419, ADR-0014).
CREATE TABLE movie_embeddings (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id      bigint NOT NULL,
    embedding     vector(768) NOT NULL,
    model_version varchar(50) NOT NULL,
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_movie_embeddings_movie_id UNIQUE (movie_id),
    CONSTRAINT fk_movie_embeddings_movie_id FOREIGN KEY (movie_id)
        REFERENCES movies (id) ON DELETE CASCADE
);

-- API-031은 코사인 거리(<=>) 오름차순과 LIMIT을 사용해 이 HNSW 인덱스를 조회한다.
CREATE INDEX ix_movie_embeddings_embedding_hnsw
    ON movie_embeddings USING hnsw (embedding vector_cosine_ops);
