-- 공통 선행 마이그레이션. 전 도메인이 FK로 참조하는 확장과 기준 테이블만 담는다.
-- 도메인별 테이블은 S15P21E106-179/180/181에서 추가한다.
-- 기준정보 Seed(popcorn_flavors 8종, otts 목록)는 코드 확정 후 별도 마이그레이션에서 넣는다.

-- 확장. vector는 이미지에 pgvector가 설치되어 있어야 한다(S15P21E106-177 협의).
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pg_trgm;


-- 팝콘 맛 기준정보. code는 불변이고 표시명·색상은 변경 가능하다(ADR-0015).
CREATE TABLE popcorn_flavors (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         varchar(30) NOT NULL,
    display_name varchar(30) NOT NULL,
    color        varchar(20) NOT NULL,
    sort_order   int NOT NULL,
    CONSTRAINT uk_popcorn_flavors_code UNIQUE (code)
);


-- 서비스 계정. 탈퇴는 물리 삭제가 아니라 status 전이 + 익명화 치환이다(D-9 계정 영역 확정).
-- 익명화로 email·nickname이 더미 값으로 바뀌므로 부분 유일 인덱스 없이 평범한 유일 제약을 쓴다.
CREATE TABLE users (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 공개 URL 노출용. 내부 식별자는 bigint를 유지한다(ADR-0008).
    public_id            uuid NOT NULL DEFAULT gen_random_uuid(),
    email                varchar(255) NOT NULL,
    -- 소셜 전용 계정과 탈퇴 계정은 NULL이다.
    password_hash        varchar(255),
    nickname             varchar(20) NOT NULL,
    -- 생년월일. 실명·나이는 수집하지 않는다(D-8).
    birth_date           date NOT NULL,
    gender               varchar(10),
    visibility           varchar(10) NOT NULL DEFAULT 'PRIVATE',
    status               varchar(30) NOT NULL,
    onboarding_completed boolean NOT NULL DEFAULT false,
    created_at           timestamptz NOT NULL DEFAULT now(),
    withdrawn_at         timestamptz,
    CONSTRAINT uk_users_public_id UNIQUE (public_id),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
    CONSTRAINT ck_users_visibility CHECK (visibility IN ('PUBLIC', 'PRIVATE')),
    CONSTRAINT ck_users_status
        CHECK (status IN ('PENDING_VERIFICATION', 'ACTIVE', 'WITHDRAWN'))
);

-- 닉네임 유일성은 공백 제거·소문자 정규화 값으로 판단한다(ERD 2.1).
-- 정규화 컬럼을 따로 두지 않고 함수 기반 유일 인덱스로 규칙을 한 곳에만 둔다.
-- 중복 확인 질의(API-016)는 반드시 같은 식을 사용해야 인덱스를 탄다.
CREATE UNIQUE INDEX uix_users_nickname_normalized
    ON users (lower(replace(nickname, ' ', '')));


-- 장르 기준정보. TMDb 장르 ID와 매핑한다.
CREATE TABLE genres (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          varchar(30) NOT NULL,
    name          text NOT NULL,
    tmdb_genre_id int NOT NULL,
    CONSTRAINT uk_genres_code UNIQUE (code),
    CONSTRAINT uk_genres_tmdb_genre_id UNIQUE (tmdb_genre_id)
);


-- OTT 기준정보. 지원 목록은 API-025 미정이므로 Seed는 넣지 않는다.
CREATE TABLE otts (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             varchar(30) NOT NULL,
    name             text NOT NULL,
    logo_url         text,
    tmdb_provider_id int NOT NULL,
    CONSTRAINT uk_otts_code UNIQUE (code),
    CONSTRAINT uk_otts_tmdb_provider_id UNIQUE (tmdb_provider_id)
);


-- 인물(감독·배우). 검색 대상이다(FR-14).
CREATE TABLE people (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_person_id int NOT NULL,
    name           text NOT NULL,
    profile_url    text,
    CONSTRAINT uk_people_tmdb_person_id UNIQUE (tmdb_person_id)
);


-- 영화 마스터(TMDb 기준). average_rating·rating_count는 평가 집계 반정규화 컬럼이다(D-10).
CREATE TABLE movies (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_id                  int NOT NULL,
    -- 학습 데이터 매핑용. 매핑되지 않는 영화가 있어 NULL을 허용한다.
    movielens_id             int,
    title                    text NOT NULL,
    original_title           text,
    synopsis                 text,
    release_date             date,
    runtime_minutes          int,
    poster_url               text,
    backdrop_url             text,
    -- K-Means 최근접 Centroid로 배정한다(ADR-0015). 배정 전에는 NULL이다.
    representative_flavor_id bigint,
    taste_model_version      varchar(50),
    average_rating           numeric(3, 2) NOT NULL DEFAULT 0,
    rating_count             int NOT NULL DEFAULT 0,
    synced_at                timestamptz,
    CONSTRAINT uk_movies_tmdb_id UNIQUE (tmdb_id),
    CONSTRAINT fk_movies_representative_flavor_id FOREIGN KEY (representative_flavor_id)
        REFERENCES popcorn_flavors (id) ON DELETE RESTRICT,
    CONSTRAINT ck_movies_average_rating_range
        CHECK (average_rating >= 0 AND average_rating <= 5),
    CONSTRAINT ck_movies_rating_count_not_negative CHECK (rating_count >= 0)
);

-- PostgreSQL은 FK 컬럼에 인덱스를 자동으로 만들지 않는다. 맛별 영화 조회에 쓰인다.
CREATE INDEX ix_movies_representative_flavor_id ON movies (representative_flavor_id);
