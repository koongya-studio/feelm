CREATE TABLE outbox_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id uuid NOT NULL,
    event_type varchar(30) NOT NULL,
    topic varchar(249) NOT NULL,
    partition_key bigint NOT NULL,
    message jsonb NOT NULL,
    status varchar(20) NOT NULL,
    attempt_count integer NOT NULL,
    next_attempt_at timestamptz NOT NULL,
    last_attempt_at timestamptz,
    last_error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    published_at timestamptz,
    CONSTRAINT uk_outbox_events_event_id UNIQUE (event_id),
    CONSTRAINT ck_outbox_events_status CHECK (status IN ('PENDING', 'PUBLISHED')),
    CONSTRAINT ck_outbox_events_attempt_count CHECK (attempt_count >= 0),
    CONSTRAINT ck_outbox_events_published_state CHECK (
        (status = 'PENDING' AND published_at IS NULL)
        OR (status = 'PUBLISHED' AND published_at IS NOT NULL)
    ),
    CONSTRAINT ck_outbox_events_message_contract CHECK (
        jsonb_typeof(message) = 'object'
        AND message ?& ARRAY['eventId', 'eventType', 'occurredAt', 'userId', 'payload']
        AND jsonb_typeof(message -> 'payload') = 'object'
        AND message ->> 'eventId' = event_id::text
        AND message ->> 'eventType' = event_type
        AND message ->> 'userId' = partition_key::text
    )
);

CREATE INDEX ix_outbox_events_pending_due
    ON outbox_events (next_attempt_at, id)
    WHERE status = 'PENDING';

CREATE INDEX ix_outbox_events_published_at
    ON outbox_events (published_at)
    WHERE status = 'PUBLISHED';
