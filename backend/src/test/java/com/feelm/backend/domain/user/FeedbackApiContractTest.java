package com.feelm.backend.domain.user;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.http.MediaType;

class FeedbackApiContractTest extends UserProfileApiTestSupport {

    @BeforeEach
    void feedbackTable() {
        jdbcTemplate.execute(
                """
                CREATE TABLE IF NOT EXISTS user_feedback (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    category varchar(20) NOT NULL,
                    satisfaction varchar(20),
                    comment varchar(1000),
                    screen_path varchar(300) NOT NULL,
                    movie_id bigint,
                    recommendation_type varchar(30),
                    created_at timestamp with time zone NOT NULL DEFAULT current_timestamp,
                    notification_sent_at timestamp with time zone
                )
                """);
        jdbcTemplate.update("DELETE FROM user_feedback");
    }

    @Test
    void submitPersistsContext() throws Exception {
        long userId = activeUser("feedback@example.com", "의견사용자");
        mockMvc.perform(
                        post("/api/v1/feedback")
                                .header("Authorization", bearerFor(userId))
                                .contentType(MediaType.APPLICATION_JSON)
                                .content(
                                        """
                                {"category":"RECOMMENDATION","satisfaction":"GOOD",
                                 "comment":"좋은 추천이에요","screenPath":"/app/recommendations",
                                 "recommendationType":"TODAY"}
                                """))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.id").isNumber())
                .andExpect(jsonPath("$.createdAt").exists());
        assertThat(
                        jdbcTemplate.queryForObject(
                                "SELECT screen_path FROM user_feedback WHERE user_id = ?",
                                String.class,
                                userId))
                .isEqualTo("/app/recommendations");
    }

    @Test
    void rejectsInvalidSubmission() throws Exception {
        long userId = activeUser("feedback@example.com", "의견사용자");
        for (String payload :
                new String[] {
                    "{\"category\":\"GENERAL\",\"screenPath\":\"https://evil.example\"}",
                    "{\"category\":\"GENERAL\",\"screenPath\":\"/app/search\"}",
                    "{\"category\":\"GENERAL\",\"screenPath\":\"/app/search\",\"comment\":\""
                            + "x".repeat(1001)
                            + "\"}",
                    "{\"category\":\"GENERAL\",\"screenPath\":\"/app/search\",\"comment\":\"ok\",\"recommendationType\":\"@channel\"}"
                }) {
            mockMvc.perform(
                            post("/api/v1/feedback")
                                    .header("Authorization", bearerFor(userId))
                                    .contentType(MediaType.APPLICATION_JSON)
                                    .content(payload))
                    .andExpect(status().isBadRequest())
                    .andExpect(jsonPath("$.code").value("VALIDATION_FAILED"));
        }
        assertThat(jdbcTemplate.queryForObject("SELECT count(*) FROM user_feedback", Long.class))
                .isZero();
    }

    @Test
    void requiresAuthentication() throws Exception {
        mockMvc.perform(
                        post("/api/v1/feedback")
                                .contentType(MediaType.APPLICATION_JSON)
                                .content(
                                        """
                                {"category":"GENERAL","comment":"의견","screenPath":"/app/my/settings"}
                                """))
                .andExpect(status().isUnauthorized());
    }

    @Test
    void withdrawnAccountCannotSubmitWithAnOldToken() throws Exception {
        long userId = activeUser("feedback@example.com", "의견사용자");
        jdbcTemplate.update("UPDATE users SET status = 'WITHDRAWN' WHERE id = ?", userId);
        mockMvc.perform(
                        post("/api/v1/feedback")
                                .header("Authorization", bearerFor(userId))
                                .contentType(MediaType.APPLICATION_JSON)
                                .content(
                                        """
                                {"category":"GENERAL","comment":"뒤늦은 의견","screenPath":"/app/my/settings"}
                                """))
                .andExpect(status().isUnauthorized());
        assertThat(jdbcTemplate.queryForObject("SELECT count(*) FROM user_feedback", Long.class))
                .isZero();
    }
}
