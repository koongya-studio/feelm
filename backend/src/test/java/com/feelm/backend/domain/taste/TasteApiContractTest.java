package com.feelm.backend.domain.taste;

import static org.hamcrest.Matchers.hasSize;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import com.feelm.backend.global.security.TokenProvider;
import com.feelm.backend.support.SharedTestRuntime;
import java.math.BigDecimal;
import java.sql.Timestamp;
import java.time.Instant;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.web.servlet.MockMvc;

@SpringBootTest(properties = "spring.jpa.hibernate.ddl-auto=none")
@AutoConfigureMockMvc
@DisplayName("취향 조회 API — API-041·044 계약")
@SharedTestRuntime
class TasteApiContractTest {

    private static final String POPCORN_PATH = "/api/v1/users/me/popcorn";
    private static final String FLAVORS_PATH = "/api/v1/popcorn-flavors";

    @Autowired private MockMvc mockMvc;
    @Autowired private JdbcTemplate jdbcTemplate;
    @Autowired private TokenProvider tokenProvider;

    @BeforeEach
    void setUpSchema() {
        jdbcTemplate.execute("DROP TABLE IF EXISTS ratings");
        jdbcTemplate.execute("DROP TABLE IF EXISTS movies");
        jdbcTemplate.execute("DROP TABLE IF EXISTS popcorn_flavors");
        jdbcTemplate.execute(
                """
                CREATE TABLE popcorn_flavors (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    code varchar(30) NOT NULL UNIQUE,
                    display_name varchar(30) NOT NULL,
                    color varchar(20) NOT NULL,
                    sort_order int NOT NULL,
                    cluster_id int NOT NULL UNIQUE,
                    representative_keywords json NOT NULL
                )
                """);
        jdbcTemplate.execute(
                """
                CREATE TABLE movies (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    title varchar(255) NOT NULL,
                    representative_flavor_id bigint
                )
                """);
        jdbcTemplate.execute(
                """
                CREATE TABLE ratings (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id bigint NOT NULL,
                    movie_id bigint NOT NULL,
                    score numeric(2, 1) NOT NULL,
                    created_at timestamp with time zone NOT NULL
                )
                """);
    }

    @Test
    @DisplayName("팝콘 맛 기준정보는 인증 없이 표시 순서대로 조회되고 원시 군집 ID를 노출하지 않는다")
    void popcornFlavorsArePublicAndHideClusterId() throws Exception {
        insertFlavor(1, "FLAVOR_B", "두 번째 맛", "#222222", 2, 7, "[\"여운\",\"성장\"]");
        insertFlavor(2, "FLAVOR_A", "첫 번째 맛", "#111111", 1, 3, "[\"긴장\",\"반전\"]");

        mockMvc.perform(get(FLAVORS_PATH))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.items", hasSize(2)))
                .andExpect(jsonPath("$.items[0].code").value("FLAVOR_A"))
                .andExpect(jsonPath("$.items[0].displayName").value("첫 번째 맛"))
                .andExpect(jsonPath("$.items[0].color").value("#111111"))
                .andExpect(jsonPath("$.items[0].representativeKeywords[0]").value("긴장"))
                .andExpect(jsonPath("$.items[0].representativeKeywords[1]").value("반전"))
                .andExpect(jsonPath("$.items[0].sortOrder").value(1))
                .andExpect(jsonPath("$.items[0].clusterId").doesNotExist());
    }

    @Test
    @DisplayName("팝콘 버킷은 인증이 필요하다")
    void popcornBucketRequiresAuthentication() throws Exception {
        mockMvc.perform(get(POPCORN_PATH))
                .andExpect(status().isUnauthorized())
                .andExpect(jsonPath("$.code").value("UNAUTHORIZED"));
    }

    @Test
    @DisplayName("사용자 평가를 맛별로 집계하고 빈 맛을 포함한 8개 맛을 모두 반환한다")
    void popcornBucketAggregatesRatingsByFlavor() throws Exception {
        for (int order = 1; order <= 8; order++) {
            insertFlavor(
                    order,
                    "FLAVOR_" + order,
                    "맛 " + order,
                    "#00000" + order,
                    order,
                    order - 1,
                    "[\"키워드" + order + "\"]");
        }

        insertMovie(101, "영화 A", 1L);
        insertMovie(102, "영화 B", 1L);
        insertMovie(103, "영화 C", 2L);
        insertMovie(104, "미분류 영화", null);
        insertRating(1, 10, 101, "4.5", "2026-07-03T00:00:00Z");
        insertRating(2, 10, 102, "3.5", "2026-07-01T00:00:00Z");
        insertRating(3, 10, 103, "5.0", "2026-07-02T00:00:00Z");
        insertRating(4, 10, 104, "1.0", "2026-07-04T00:00:00Z");
        insertRating(5, 99, 101, "1.0", "2026-06-01T00:00:00Z");

        mockMvc.perform(get(POPCORN_PATH).header("Authorization", "Bearer " + accessTokenFor(10)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.totalCount").value(3))
                .andExpect(jsonPath("$.newFlavorThreshold").doesNotExist())
                .andExpect(jsonPath("$.flavors", hasSize(8)))
                .andExpect(jsonPath("$.flavors[0].flavorCode").value("FLAVOR_1"))
                .andExpect(jsonPath("$.flavors[0].popcornCount").value(2))
                .andExpect(jsonPath("$.flavors[0].averageScore").value(4.0))
                .andExpect(jsonPath("$.flavors[0].isNewFlavor").doesNotExist())
                .andExpect(jsonPath("$.flavors[0].discoveredAt").value("2026-07-01T00:00:00Z"))
                .andExpect(jsonPath("$.flavors[1].popcornCount").value(1))
                .andExpect(jsonPath("$.flavors[1].averageScore").value(5.0))
                .andExpect(jsonPath("$.flavors[7].popcornCount").value(0))
                .andExpect(jsonPath("$.flavors[7].averageScore").isEmpty())
                .andExpect(jsonPath("$.flavors[7].discoveredAt").isEmpty());
    }

    private String accessTokenFor(long userId) {
        return tokenProvider.createAccessToken(userId);
    }

    private void insertFlavor(
            long id,
            String code,
            String displayName,
            String color,
            int sortOrder,
            int clusterId,
            String keywords) {
        jdbcTemplate.update(
                """
                INSERT INTO popcorn_flavors
                    (id, code, display_name, color, sort_order, cluster_id, representative_keywords)
                VALUES (?, ?, ?, ?, ?, ?, ? FORMAT JSON)
                """,
                id,
                code,
                displayName,
                color,
                sortOrder,
                clusterId,
                keywords);
    }

    private void insertMovie(long id, String title, Long flavorId) {
        jdbcTemplate.update(
                "INSERT INTO movies (id, title, representative_flavor_id) VALUES (?, ?, ?)",
                id,
                title,
                flavorId);
    }

    private void insertRating(long id, long userId, long movieId, String score, String createdAt) {
        jdbcTemplate.update(
                """
                INSERT INTO ratings (id, user_id, movie_id, score, created_at)
                VALUES (?, ?, ?, ?, ?)
                """,
                id,
                userId,
                movieId,
                new BigDecimal(score),
                Timestamp.from(Instant.parse(createdAt)));
    }
}
