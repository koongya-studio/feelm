package com.feelm.backend.domain.user;

import com.feelm.backend.global.security.TokenProvider;
import com.feelm.backend.support.SharedTestRuntime;
import java.math.BigDecimal;
import java.sql.Date;
import java.sql.Timestamp;
import java.time.Instant;
import org.junit.jupiter.api.BeforeEach;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.web.servlet.MockMvc;
import tools.jackson.databind.ObjectMapper;

/**
 * 사용자 프로필 API(API-014~016) 계약 테스트의 공통 골격이다.
 *
 * <p>스키마를 직접 만든다({@code ddl-auto=none}). 프로필 요약이 세는 {@code frames}·{@code ratings}는 아직 Entity가 없어
 * JPA가 만들어 주지 못하고, 팝콘 수는 {@code movies}·{@code popcorn_flavors}까지 필요하기 때문이다. 취향 API 계약 테스트가 같은 방식을
 * 쓴다.
 *
 * <p>{@code users}와 {@code user_auth_providers}는 JPA가 관리하는 테이블이라 다른 테스트 컨텍스트가 이미 만들어 두었을 수 있다. 그래서
 * 지우고 다시 만들지 않고 없을 때만 만든 뒤 행만 비운다. 반대로 취향 쪽 테이블은 테스트마다 열 구성이 달라 매번 다시 만든다.
 */
@SpringBootTest(properties = "spring.jpa.hibernate.ddl-auto=none")
@SharedTestRuntime
@AutoConfigureMockMvc
abstract class UserProfileApiTestSupport {

    protected static final String ME_PATH = "/api/v1/users/me";
    protected static final String NICKNAME_PATH = "/api/v1/users/nickname-availability";

    /** 이 골격이 만든 계정만 골라내는 조건. 다른 테스트가 남긴 계정을 지우지 않는다. */
    private static final String TEST_EMAIL_PATTERN = "%@example.com";

    protected static final String BIRTH_DATE = "1999-03-14";
    protected static final String CREATED_AT = "2026-08-01T00:00:00Z";

    @Autowired protected MockMvc mockMvc;
    @Autowired protected JdbcTemplate jdbcTemplate;
    @Autowired protected TokenProvider tokenProvider;
    @Autowired protected ObjectMapper objectMapper;

    @BeforeEach
    void setUpSchema() {
        createAccountTablesIfAbsent();
        recreateTasteTables();
        // H2 인스턴스를 모든 테스트 컨텍스트가 공유하므로 이 골격이 넣은 행만 지운다(리뷰 A-13).
        jdbcTemplate.update(
                "DELETE FROM user_auth_providers WHERE user_id IN"
                        + " (SELECT id FROM users WHERE email LIKE ?)",
                TEST_EMAIL_PATTERN);
        jdbcTemplate.update("DELETE FROM users WHERE email LIKE ?", TEST_EMAIL_PATTERN);
    }

    private void createAccountTablesIfAbsent() {
        jdbcTemplate.execute(
                """
                CREATE TABLE IF NOT EXISTS users (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    public_id uuid,
                    email varchar(255) NOT NULL,
                    password_hash varchar(255),
                    nickname varchar(20) NOT NULL,
                    birth_date date,
                    gender varchar(10),
                    visibility varchar(10) NOT NULL,
                    status varchar(30) NOT NULL,
                    onboarding_completed boolean NOT NULL,
                    created_at timestamp with time zone NOT NULL,
                    withdrawn_at timestamp with time zone
                )
                """);
        jdbcTemplate.execute(
                """
                CREATE TABLE IF NOT EXISTS user_auth_providers (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id bigint NOT NULL,
                    provider varchar(20) NOT NULL,
                    provider_user_id varchar(255) NOT NULL,
                    linked_at timestamp with time zone NOT NULL
                )
                """);
    }

    private void recreateTasteTables() {
        jdbcTemplate.execute("DROP TABLE IF EXISTS frames");
        jdbcTemplate.execute("DROP TABLE IF EXISTS ratings");
        jdbcTemplate.execute("DROP TABLE IF EXISTS movies");
        jdbcTemplate.execute("DROP TABLE IF EXISTS popcorn_flavors");
        jdbcTemplate.execute(
                """
                CREATE TABLE popcorn_flavors (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    code varchar(30) NOT NULL UNIQUE,
                    display_name varchar(30) NOT NULL,
                    color varchar(20) NOT NULL,
                    sort_order int NOT NULL,
                    cluster_id int NOT NULL UNIQUE,
                    representative_keywords json NOT NULL
                )
                """);
        jdbcTemplate.execute(
                """
                CREATE TABLE movies (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    title varchar(255) NOT NULL,
                    representative_flavor_id bigint
                )
                """);
        jdbcTemplate.execute(
                """
                CREATE TABLE ratings (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id bigint NOT NULL,
                    movie_id bigint NOT NULL,
                    score numeric(2, 1) NOT NULL,
                    created_at timestamp with time zone NOT NULL
                )
                """);
        jdbcTemplate.execute(
                """
                CREATE TABLE frames (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    rating_id bigint NOT NULL,
                    user_id bigint NOT NULL,
                    movie_id bigint NOT NULL,
                    created_at timestamp with time zone NOT NULL
                )
                """);
    }

    /** 이메일 가입으로 만든 활성 계정. 비밀번호 해시가 있어 {@code hasPassword}가 참이다. */
    protected long activeUser(String email, String nickname) {
        return insertUser(email, "$2a$10$hash", nickname, "ACTIVE", "PRIVATE", false);
    }

    /** 소셜 전용 활성 계정. 비밀번호 해시가 없다. */
    protected long socialOnlyUser(String email, String nickname) {
        return insertUser(email, null, nickname, "ACTIVE", "PRIVATE", false);
    }

    protected long insertUser(
            String email,
            String passwordHash,
            String nickname,
            String status,
            String visibility,
            boolean onboardingCompleted) {
        jdbcTemplate.update(
                """
                INSERT INTO users
                    (email, password_hash, nickname, birth_date, gender, visibility, status,
                     onboarding_completed, created_at)
                VALUES (?, ?, ?, ?, 'FEMALE', ?, ?, ?, ?)
                """,
                email,
                passwordHash,
                nickname,
                Date.valueOf(BIRTH_DATE),
                visibility,
                status,
                onboardingCompleted,
                Timestamp.from(Instant.parse(CREATED_AT)));
        return jdbcTemplate.queryForObject(
                "SELECT id FROM users WHERE email = ?", Long.class, email);
    }

    protected void linkProvider(long userId, String provider) {
        jdbcTemplate.update(
                """
                INSERT INTO user_auth_providers (user_id, provider, provider_user_id, linked_at)
                VALUES (?, ?, ?, ?)
                """,
                userId,
                provider,
                provider.toLowerCase() + "-" + userId,
                Timestamp.from(Instant.parse(CREATED_AT)));
    }

    protected void insertFlavor(long id, String code, int order) {
        jdbcTemplate.update(
                """
                INSERT INTO popcorn_flavors
                    (id, code, display_name, color, sort_order, cluster_id, representative_keywords)
                VALUES (?, ?, ?, ?, ?, ?, ? FORMAT JSON)
                """,
                id,
                code,
                "맛 " + order,
                "#00000" + order,
                order,
                order,
                "[\"키워드" + order + "\"]");
    }

    protected void insertMovie(long id, String title, Long flavorId) {
        jdbcTemplate.update(
                "INSERT INTO movies (id, title, representative_flavor_id) VALUES (?, ?, ?)",
                id,
                title,
                flavorId);
    }

    protected void insertRating(long id, long userId, long movieId, String score) {
        jdbcTemplate.update(
                """
                INSERT INTO ratings (id, user_id, movie_id, score, created_at)
                VALUES (?, ?, ?, ?, ?)
                """,
                id,
                userId,
                movieId,
                new BigDecimal(score),
                Timestamp.from(Instant.parse(CREATED_AT)));
    }

    protected void insertFrame(long id, long ratingId, long userId, long movieId) {
        jdbcTemplate.update(
                """
                INSERT INTO frames (id, rating_id, user_id, movie_id, created_at)
                VALUES (?, ?, ?, ?, ?)
                """,
                id,
                ratingId,
                userId,
                movieId,
                Timestamp.from(Instant.parse(CREATED_AT)));
    }

    protected String bearerFor(long userId) {
        return "Bearer " + tokenProvider.createAccessToken(userId);
    }

    protected String nicknameOf(long userId) {
        return jdbcTemplate.queryForObject(
                "SELECT nickname FROM users WHERE id = ?", String.class, userId);
    }
}
