package com.feelm.backend.domain.taste;

import static org.hamcrest.Matchers.hasSize;
import static org.hamcrest.Matchers.nullValue;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import com.feelm.backend.global.security.TokenProvider;
import com.feelm.backend.support.SharedTestRuntime;
import java.sql.Timestamp;
import java.time.Instant;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.web.servlet.MockMvc;

@SpringBootTest(properties = "spring.jpa.hibernate.ddl-auto=none")
@AutoConfigureMockMvc
@DisplayName("취향 분석·키워드 조회 API — API-040 계약")
@SharedTestRuntime
class TasteAnalysisApiContractTest {

    private static final String TASTE_PATH = "/api/v1/users/me/taste";

    @Autowired private MockMvc mockMvc;
    @Autowired private JdbcTemplate jdbcTemplate;
    @Autowired private TokenProvider tokenProvider;

    @BeforeEach
    void setUpSchema() {
        jdbcTemplate.execute("DROP TABLE IF EXISTS taste_analyses");
        jdbcTemplate.execute(
                """
                CREATE TABLE taste_analyses (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id bigint NOT NULL UNIQUE,
                    analysis json NOT NULL,
                    keywords json NOT NULL,
                    rating_count int NOT NULL,
                    analyzed_at timestamp with time zone NOT NULL
                )
                """);
    }

    @Test
    @DisplayName("취향 분석 조회는 인증이 필요하다")
    void tasteAnalysisRequiresAuthentication() throws Exception {
        mockMvc.perform(get(TASTE_PATH))
                .andExpect(status().isUnauthorized())
                .andExpect(jsonPath("$.code").value("UNAUTHORIZED"));
    }

    @Test
    @DisplayName("캐시가 없는 사용자는 평가가 부족한 빈 분석을 조회한다")
    void returnsEmptyTasteForUserWithoutRatings() throws Exception {
        mockMvc.perform(get(TASTE_PATH).header("Authorization", "Bearer " + accessTokenFor(10)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.ratingCount").value(0))
                .andExpect(jsonPath("$.insufficientData").value(true))
                .andExpect(jsonPath("$.analysis.genres", hasSize(0)))
                .andExpect(jsonPath("$.analysis.countries", hasSize(0)))
                .andExpect(jsonPath("$.analysis.eras", hasSize(0)))
                .andExpect(jsonPath("$.analysis.directors", hasSize(0)))
                .andExpect(jsonPath("$.keywords", hasSize(0)))
                .andExpect(jsonPath("$.analyzedAt").value(nullValue()));
    }

    @Test
    @DisplayName("인증 사용자의 캐시된 분석과 키워드만 계약 형식으로 반환한다")
    void returnsCachedAnalysisForAuthenticatedUser() throws Exception {
        insertTasteAnalysis(
                1,
                10,
                """
                {
                  "genres": [{"code":"THRILLER","name":"스릴러","count":12,"averageScore":4.4,"share":0.29}],
                  "countries": [{"code":"KR","name":"한국","count":15,"averageScore":4.1,"share":0.36}],
                  "eras": [{"label":"2010s","count":20,"averageScore":4.0,"share":0.48}],
                  "directors": [{"personId":7467,"name":"데이비드 핀처","count":3,"averageScore":4.7}]
                }
                """,
                "[{\"code\":\"DARK_THRILLER_LOVER\",\"label\":\"어둠 속 스릴러 애호가\"}]",
                42,
                "2026-08-30T05:21:00Z");
        insertTasteAnalysis(
                2,
                99,
                "{\"genres\":[],\"countries\":[],\"eras\":[],\"directors\":[]}",
                "[]",
                1,
                "2026-08-31T00:00:00Z");

        mockMvc.perform(get(TASTE_PATH).header("Authorization", "Bearer " + accessTokenFor(10)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.ratingCount").value(42))
                .andExpect(jsonPath("$.insufficientData").value(false))
                .andExpect(jsonPath("$.analysis.genres", hasSize(1)))
                .andExpect(jsonPath("$.analysis.genres[0].code").value("THRILLER"))
                .andExpect(jsonPath("$.analysis.genres[0].name").value("스릴러"))
                .andExpect(jsonPath("$.analysis.genres[0].count").value(12))
                .andExpect(jsonPath("$.analysis.genres[0].averageScore").value(4.4))
                .andExpect(jsonPath("$.analysis.genres[0].share").value(0.29))
                .andExpect(jsonPath("$.analysis.countries[0].code").value("KR"))
                .andExpect(jsonPath("$.analysis.eras[0].label").value("2010s"))
                .andExpect(jsonPath("$.analysis.directors[0].personId").value(7467))
                .andExpect(jsonPath("$.keywords", hasSize(1)))
                .andExpect(jsonPath("$.keywords[0].code").value("DARK_THRILLER_LOVER"))
                .andExpect(jsonPath("$.keywords[0].label").value("어둠 속 스릴러 애호가"))
                .andExpect(jsonPath("$.analyzedAt").value("2026-08-30T05:21:00Z"));
    }

    @Test
    @DisplayName("키워드가 비어 있는 캐시는 평가 데이터가 부족한 결과로 반환한다")
    void marksCachedResultWithoutKeywordsAsInsufficient() throws Exception {
        insertTasteAnalysis(
                1,
                10,
                "{\"genres\":[],\"countries\":[],\"eras\":[],\"directors\":[]}",
                "[]",
                1,
                "2026-08-31T00:00:00Z");

        mockMvc.perform(get(TASTE_PATH).header("Authorization", "Bearer " + accessTokenFor(10)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.ratingCount").value(1))
                .andExpect(jsonPath("$.insufficientData").value(true))
                .andExpect(jsonPath("$.analysis.genres", hasSize(0)))
                .andExpect(jsonPath("$.keywords", hasSize(0)))
                .andExpect(jsonPath("$.analyzedAt").value("2026-08-31T00:00:00Z"));
    }

    @Test
    @DisplayName("캐시 JSON의 분석 배열이 누락되면 빈 배열로 반환한다")
    void treatsMissingAnalysisArraysAsEmpty() throws Exception {
        insertTasteAnalysis(
                1,
                10,
                "{\"genres\":[],\"eras\":[],\"directors\":[]}",
                "[]",
                3,
                "2026-08-30T05:21:00Z");

        mockMvc.perform(get(TASTE_PATH).header("Authorization", "Bearer " + accessTokenFor(10)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.analysis.countries", hasSize(0)))
                .andExpect(jsonPath("$.insufficientData").value(true));
    }

    @Test
    @DisplayName("캐시 JSON의 알 수 없는 필드는 무시한다")
    void ignoresUnknownCacheFields() throws Exception {
        insertTasteAnalysis(
                1,
                10,
                """
                {
                  "genres": [{"code":"THRILLER","name":"스릴러","count":1,"averageScore":4.0,"share":1.0,"posterUrl":"ignored"}],
                  "countries": [],
                  "eras": [],
                  "directors": [],
                  "version": 2
                }
                """,
                "[{\"code\":\"THRILLER_LOVER\",\"label\":\"스릴러 애호가\",\"score\":0.9}]",
                5,
                "2026-08-30T05:21:00Z");

        mockMvc.perform(get(TASTE_PATH).header("Authorization", "Bearer " + accessTokenFor(10)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.analysis.genres[0].code").value("THRILLER"))
                .andExpect(jsonPath("$.keywords[0].code").value("THRILLER_LOVER"))
                .andExpect(jsonPath("$.insufficientData").value(false));
    }

    private String accessTokenFor(long userId) {
        return tokenProvider.createAccessToken(userId);
    }

    private void insertTasteAnalysis(
            long id,
            long userId,
            String analysis,
            String keywords,
            int ratingCount,
            String analyzedAt) {
        jdbcTemplate.update(
                """
                INSERT INTO taste_analyses
                    (id, user_id, analysis, keywords, rating_count, analyzed_at)
                VALUES (?, ?, ? FORMAT JSON, ? FORMAT JSON, ?, ?)
                """,
                id,
                userId,
                analysis,
                keywords,
                ratingCount,
                Timestamp.from(Instant.parse(analyzedAt)));
    }
}
