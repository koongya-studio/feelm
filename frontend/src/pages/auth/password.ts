/** 화면에 보이는 문구. 검사 규칙과 어긋나지 않도록 한 곳에서 쓴다 */
export const PASSWORD_HINT = '8~64자, 영문·숫자·특수문자 포함';

/**
 * 서버의 검사식과 같은 규칙이다(`SignupRequest.PASSWORD_PATTERN`).
 *
 * 허용 문자는 공백을 제외한 아스키 출력 가능 문자이고, 그 안에서 영문·숫자가 아닌
 * 문자가 곧 특수문자다. 한쪽만 바뀌면 화면과 서버의 판정이 갈리므로 식을 그대로 옮긴다.
 */
const PASSWORD_PATTERN = /^(?=.*[A-Za-z])(?=.*[0-9])(?=.*[^A-Za-z0-9])[\x21-\x7E]{8,64}$/;

/** 8~64자이면서 영문·숫자·특수문자를 각각 1자 이상 포함하는지 */
export function isValidPassword(value: string) {
  return PASSWORD_PATTERN.test(value);
}
