/*
 * 포스터 자리표시자 색조.
 *
 * **실제 포스터 이미지의 권리가 확정되지 않아 목업 단계에서는 자리표시자가 화면의
 * 절반을 차지한다**(`PRODUCT.md`). 실제 이미지가 들어오면 이 값은 쓰이지 않는다
 * (`design-concept.md` 5장 — 포스터는 TMDb 이미지를 그대로 쓴다).
 *
 * **무채색이다.** 이전 값은 유채색 8종(세피아 · 옥스블러드 · 딥 그린 …)이었고 폐기된
 * 이전 시각 방향에서 나온 것이었다. 확정 방향은 `UI에 유채색을 쓰지 않는다`이고
 * (`design-concept.md` 3장), **화면에 색이 보이면 그것은 콘텐츠**라는 규칙에
 * 예외를 두지 않는다. 이미지가 없는 자리는 콘텐츠가 아니므로 색을 가질 수 없다.
 * 2026-09-11에 잉크 계열 무채색으로 교체했다.
 *
 * 밝기만 4단계로 다르다. 포스터가 여러 장 나란히 놓일 때 서로 구분되게 하려는 것이고,
 * 색조(hue) 차이는 쓰지 않는다. `seed`(보통 `movieId`)로 고르므로 같은 영화는 항상
 * 같은 밝기다.
 *
 * 값은 잉크 계열에서 뽑았다(`--color-ink` #262729 ~ `--color-ink-muted` #6a6b70).
 * 밝은 벽에 어두운 것이 걸린 모양이 되어 확정 방향과 맞는다.
 */

const TONES: [string, string][] = [
  ['#262729', '#3c3d42'],
  ['#2e2f33', '#46474d'],
  ['#34353a', '#4e4f55'],
  ['#3c3d42', '#54555b'],
];

/**
 * `seed`가 고르는 색조 두 개. 어두운 쪽 · 밝은 쪽으로 대각 그라데이션을 만든다.
 * 보통 `movieId`를 넘긴다. 같은 영화는 항상 같은 값이다.
 */
export function posterTone(seed: number): [string, string] {
  return TONES[Math.abs(Math.trunc(seed)) % TONES.length];
}
